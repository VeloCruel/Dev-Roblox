-- ─── ACCESS CHECK ───────────────────────────────────────────────────────────
local function isAuthorized(player)
    if CONFIG.Owner == "" then return true end
    if player.Name == CONFIG.Owner then return true end
    for _, name in ipairs(CONFIG.Whitelist) do
        if name == player.Name then return true end
    end
    return false
end

if not isAuthorized(LocalPlayer) then return end

-- ─── GUI PARENT RESOLUTION ──────────────────────────────────────────────────
-- Prefer CoreGui-protected variants when running via executor, fall back to
-- PlayerGui in Studio / vanilla LocalScript contexts.
local function resolveGuiParent()
    local candidates = {}
    if typeof(gethui) == "function" then table.insert(candidates, gethui) end
    if typeof(get_hidden_gui) == "function" then table.insert(candidates, get_hidden_gui) end
    for _, fn in ipairs(candidates) do
        local ok, parent = pcall(fn)
        if ok and parent then return parent end
    end
    local ok = pcall(function() return CoreGui:GetChildren() end)
    if ok then return CoreGui end
    return LocalPlayer:WaitForChild("PlayerGui")
end

