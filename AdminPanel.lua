local function rank(name)
    if name == CONFIG.Owner then return "Owner" end
    if CONFIG.Ranks[name] then return CONFIG.Ranks[name] end
    for _, n in ipairs(CONFIG.Whitelist) do
        if n == name then return "Admin" end
    end
    return "Guest"
end

