-- ─── RESPAWN HANDLING ───────────────────────────────────────────────────────
-- When the local character respawns, every toggled feature has to be
-- re-applied since the old Humanoid / BodyMovers are gone.
LocalPlayer.CharacterAdded:Connect(function(char)
    char:WaitForChild("HumanoidRootPart")
    char:WaitForChild("Humanoid")
    task.wait(0.1)
    if State.flying       then startFly() end
    if State.noclipping   then setNoclip(true) end
    if State.walkSpeedOn  then applyWalkSpeed() end
    if State.jumpPowerOn  then applyJumpPower() end
    if State.invisible    then setInvisible(true) end
    if State.godMode      then setGodMode(true) end
    if State.spectating and State.spectating.Parent then setSpectate(State.spectating) end
end)

LocalPlayer.CharacterRemoving:Connect(function()
    -- Drop the per-character BodyMover refs so the new character starts clean.
    if Active.flyConn then Active.flyConn:Disconnect(); Active.flyConn = nil end
    Active.flyBV = nil; Active.flyBG = nil
    if Active.godConn then Active.godConn:Disconnect(); Active.godConn = nil end
end)

