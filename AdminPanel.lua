-- ─── FEATURE: FLY ───────────────────────────────────────────────────────────
local function startFly()
    local char = LocalPlayer.Character
    local hrp  = getHRP(char)
    local hum  = getHumanoid(char)
    if not hrp or not hum then return end

    Active.flyBV = make("BodyVelocity", {
        MaxForce = Vector3.new(math.huge, math.huge, math.huge),
        Velocity = Vector3.zero,
        Parent   = hrp,
    })
    Active.flyBG = make("BodyGyro", {
        MaxTorque = Vector3.new(math.huge, math.huge, math.huge),
        P         = 9e4,
        CFrame    = hrp.CFrame,
        Parent    = hrp,
    })

    Active.flyConn = RunService.RenderStepped:Connect(function()
        if not Active.flyBV or not Active.flyBV.Parent then return end
        local cam = Workspace.CurrentCamera
        local dir = Vector3.zero
        if UserInputService:IsKeyDown(Enum.KeyCode.W) then dir = dir + cam.CFrame.LookVector end
        if UserInputService:IsKeyDown(Enum.KeyCode.S) then dir = dir - cam.CFrame.LookVector end
        if UserInputService:IsKeyDown(Enum.KeyCode.A) then dir = dir - cam.CFrame.RightVector end
        if UserInputService:IsKeyDown(Enum.KeyCode.D) then dir = dir + cam.CFrame.RightVector end
        if UserInputService:IsKeyDown(Enum.KeyCode.Space) then dir = dir + Vector3.new(0, 1, 0) end
        if UserInputService:IsKeyDown(Enum.KeyCode.LeftControl) then dir = dir - Vector3.new(0, 1, 0) end
        Active.flyBV.Velocity = (dir.Magnitude > 0 and dir.Unit or Vector3.zero) * State.flySpeed
        Active.flyBG.CFrame   = cam.CFrame
    end)
    hum.PlatformStand = true
end

local function stopFly()
    if Active.flyConn then Active.flyConn:Disconnect(); Active.flyConn = nil end
    if Active.flyBV   then Active.flyBV:Destroy();      Active.flyBV   = nil end
    if Active.flyBG   then Active.flyBG:Destroy();      Active.flyBG   = nil end
    local hum = getHumanoid()
    if hum then hum.PlatformStand = false end
end

local function setFly(on)
    State.flying = on
    if on then startFly() else stopFly() end
end

