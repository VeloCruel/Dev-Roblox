    State.tracersOn = on
    if Active.tracerConn then Active.tracerConn:Disconnect(); Active.tracerConn = nil end
    for p in pairs(TracerLines) do clearTracer(p) end
    if not on then return end

    for _, p in ipairs(Players:GetPlayers()) do makeTracer(p) end

    Active.tracerConn = RunService.RenderStepped:Connect(function()
        local viewport = Camera.ViewportSize
        local originX, originY = viewport.X / 2, viewport.Y
        for p, line in pairs(TracerLines) do
            local char = p.Character
            local hrp  = char and char:FindFirstChild("HumanoidRootPart")
            if hrp then
                local screen, onScreen = Camera:WorldToViewportPoint(hrp.Position)
                if onScreen then
                    local dx, dy = screen.X - originX, screen.Y - originY
                    local dist   = math.sqrt(dx * dx + dy * dy)
                    line.Visible  = true
                    line.Size     = UDim2.fromOffset(2, dist)
                    line.Position = UDim2.fromOffset(originX, originY)
                    line.Rotation = math.deg(math.atan2(dy, dx)) - 90
                else
                    line.Visible = false
                end
            else
                line.Visible = false
            end
        end
    end)
end

