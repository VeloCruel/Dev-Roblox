local function createTab(name, label)
    local btn = make("TextButton", {
        Name                   = "Tab_" .. name,
        BackgroundColor3       = Color3.fromRGB(20, 22, 28),
        BackgroundTransparency = 1,
        BorderSizePixel        = 0,
        Size                   = UDim2.new(1, 0, 0, 32),
        Font                   = Enum.Font.GothamMedium,
        Text                   = label,
        TextColor3             = Color3.fromRGB(160, 165, 180),
        TextSize               = 13,
        AutoButtonColor        = false,
        Parent                 = sidebar,
    })
    make("UICorner", { CornerRadius = UDim.new(0, 6), Parent = btn })

    -- Accent strip (left side) used to mark the active tab.
    local strip = make("Frame", {
        BackgroundColor3       = CONFIG.AccentColor,
        BorderSizePixel        = 0,
        Position               = UDim2.new(0, 0, 0.5, -8),
        Size                   = UDim2.new(0, 0, 0, 16),
        Parent                 = btn,
    })
    make("UICorner", { CornerRadius = UDim.new(0, 2), Parent = strip })

    local page = make("ScrollingFrame", {
        Name                       = "Page_" .. name,
        BackgroundTransparency     = 1,
        BorderSizePixel            = 0,
        Size                       = UDim2.fromScale(1, 1),
        Position                   = UDim2.fromOffset(0, 12),
        CanvasSize                 = UDim2.new(),
        AutomaticCanvasSize        = Enum.AutomaticSize.Y,
        ScrollBarThickness         = 3,
        ScrollBarImageColor3       = CONFIG.AccentColor,
        ScrollingDirection         = Enum.ScrollingDirection.Y,
        Visible                    = false,
        Parent                     = content,
    })
    make("UIPadding", {
        PaddingTop    = UDim.new(0, 4),  PaddingBottom = UDim.new(0, 12),
        PaddingLeft   = UDim.new(0, 12), PaddingRight  = UDim.new(0, 12),
        Parent        = page,
    })
    make("UIListLayout", {
        Padding   = UDim.new(0, 6),
        SortOrder = Enum.SortOrder.LayoutOrder,
        Parent    = page,
    })

    tabs[name] = { button = btn, page = page, strip = strip }
    btn.MouseEnter:Connect(function()
        if currentTab ~= name then
            tween(btn, QuickTween, { BackgroundTransparency = 0.4 })
        end
    end)
    btn.MouseLeave:Connect(function()
        if currentTab ~= name then
            tween(btn, QuickTween, { BackgroundTransparency = 1 })
        end
    end)
    return page
end

local function selectTab(name)
    if currentTab == name then return end
    for n, t in pairs(tabs) do
        local active = (n == name)
        t.page.Visible = active
        tween(t.button, QuickTween, {
            BackgroundTransparency = active and 0.2 or 1,
            TextColor3             = active and Color3.fromRGB(235, 235, 245)
                                              or Color3.fromRGB(160, 165, 180),
        })
        tween(t.strip, QuickTween, { Size = UDim2.new(0, active and 3 or 0, 0, 16) })
    end
    currentTab = name
end

