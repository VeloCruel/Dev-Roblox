-- ─── FEATURE: VEHICLE ───────────────────────────────────────────────────────
local function getVehicle()
    local char = LocalPlayer.Character
    if not char then return nil end
    local hum = char:FindFirstChildOfClass("Humanoid")
    if not hum then return nil end
    local seat = hum.SeatPart
    if not seat or not seat:IsA("VehicleSeat") then return nil end
    return seat:FindFirstAncestorOfClass("Model"), seat
end

local function applyVehicleSpeed()
    local _, seat = getVehicle()
    if not seat then return end
    if not seat:GetAttribute("_origMaxSpeed") then
        seat:SetAttribute("_origMaxSpeed", seat.MaxSpeed)
        seat:SetAttribute("_origTorque",   seat.Torque)
    end
    seat.MaxSpeed = seat:GetAttribute("_origMaxSpeed") * State.vehicleSpeed
    seat.Torque   = seat:GetAttribute("_origTorque")   * (State.vehicleInsta and 4 or 1)
end

local function vehicleBoost()
    local model, seat = getVehicle()
    if not model or not seat then notify("No vehicle detected", "warn"); return end
    local primary = model.PrimaryPart or seat
    primary.AssemblyLinearVelocity = primary.AssemblyLinearVelocity + primary.CFrame.LookVector * 80
end

