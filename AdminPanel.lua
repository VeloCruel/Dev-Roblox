-- ─── KEYBIND / OPEN-CLOSE ANIMATION ─────────────────────────────────────────
local panelOpen = false
local function setPanelVisible(open)
    if open == panelOpen then return end
    panelOpen = open
    if open then
        panel.Visible        = true
        panel.Size           = UDim2.fromOffset(0, 0)
        panel.BackgroundTransparency = 1
        tween(panel, BounceTween, {
            Size                   = UDim2.fromOffset(620, 420),
            BackgroundTransparency = 0.05,
        })
    else
        local t = tween(panel, QuickTween, {
            Size                   = UDim2.fromOffset(0, 0),
            BackgroundTransparency = 1,
        })
        t.Completed:Connect(function() panel.Visible = false end)
    end
end

