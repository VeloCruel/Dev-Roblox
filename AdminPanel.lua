-- ─── COMMAND BAR ────────────────────────────────────────────────────────────
local function findPlayer(query)
    if not query or query == "" then return nil end
    query = query:lower()
    for _, p in ipairs(Players:GetPlayers()) do
        if p.Name:lower() == query then return p end
        if p.DisplayName:lower() == query then return p end
    end
    for _, p in ipairs(Players:GetPlayers()) do
        if p.Name:lower():sub(1, #query) == query then return p end
        if p.DisplayName:lower():sub(1, #query) == query then return p end
    end
    return nil
end

local function runCommand(line)
    if line == "" then return end
    if line:sub(1, #CONFIG.CommandPrefix) == CONFIG.CommandPrefix then
        line = line:sub(#CONFIG.CommandPrefix + 1)
    end
    local parts = {}
    for word in line:gmatch("%S+") do table.insert(parts, word) end
    local cmd = (parts[1] or ""):lower()
    local function arg1num(default) return tonumber(parts[2]) or default end
    local function arg1player()    return findPlayer(parts[2]) end

    if     cmd == "fly"        then setFly(not State.flying)
    elseif cmd == "unfly"      then setFly(false)
    elseif cmd == "noclip"     then setNoclip(not State.noclipping)
    elseif cmd == "clip"       then setNoclip(false)
    elseif cmd == "walkspeed"  or cmd == "ws"  then State.walkSpeed = arg1num(16); State.walkSpeedOn = true; applyWalkSpeed()
    elseif cmd == "jp" or cmd == "jumppower"   then State.jumpPower = arg1num(50); State.jumpPowerOn = true; applyJumpPower()
    elseif cmd == "infjump"    then setInfJump(not State.infJump)
    elseif cmd == "invis"      then setInvisible(not State.invisible)
    elseif cmd == "vis"        then setInvisible(false)
    elseif cmd == "god"        then setGodMode(not State.godMode)
    elseif cmd == "ungod"      then setGodMode(false)
    elseif cmd == "heal"       then heal()
    elseif cmd == "reset"      or cmd == "re" then resetCharacter()
    elseif cmd == "sit"        then sit()
    elseif cmd == "tp"         then local p = arg1player(); if p then teleportToPlayer(p) else notify("Player not found", "warn") end
    elseif cmd == "bring"      then local p = arg1player(); if p then bringPlayer(p)       else notify("Player not found", "warn") end
    elseif cmd == "spec"       then
        if parts[2] == "off" or parts[2] == nil then setSpectate(nil)
        else local p = arg1player(); if p then setSpectate(p) else notify("Player not found", "warn") end end
    elseif cmd == "freeze"     then local p = arg1player(); if p then setFreeze(p, true)  else notify("Player not found", "warn") end
    elseif cmd == "unfreeze"   then local p = arg1player(); if p then setFreeze(p, false) else notify("Player not found", "warn") end
    elseif cmd == "fov"        then State.fov     = arg1num(70);    applyFOV()
    elseif cmd == "gravity"    then State.gravity = arg1num(196.2); applyGravity()
    elseif cmd == "day"        then setTimeOfDay(14)
    elseif cmd == "night"      then setTimeOfDay(0)
    elseif cmd == "esp"        then setESP(not State.espOn)
    elseif cmd == "tracers"    then setTracers(not State.tracersOn)
    elseif cmd == "fullbright" or cmd == "fb" then setFullbright(not State.fullbrightOn)
    elseif cmd == "vboost"     then vehicleBoost()
    elseif cmd == "vfly"       then setVehicleFly(not State.vehicleFly)
    elseif cmd == "vspeed"     then State.vehicleSpeed = arg1num(1); applyVehicleSpeed()
    elseif cmd == "help"       then selectTab("info")
    else notify("Unknown command: " .. cmd, "err"); return end

    logCmd(line)
end

