--[[
================================================================================
ROBLOX ADMIN PANEL — Single-File Edition
================================================================================
A complete client-side admin panel. Everything is generated by this one file:
the ScreenGui, the tween animations, the command logic, and the respawn
handling. Drop it in as a LocalScript (StarterPlayer > StarterPlayerScripts)
or run it through an executor.

QUICK START
  1. Open the CONFIG block below.
  2. Set Owner to your username and (optionally) add Whitelist entries.
  3. Run the script.
  4. Press the keybind (default RightControl) — or tap the floating button
     on mobile — to toggle the panel.

NOTES
  • This panel is fully client-side. No RemoteEvents and no Server Script
    are required, which keeps setup beginner-friendly. Commands that target
    other players (Bring / Freeze / etc.) only have a visible effect in
    experiences where the engine allows client-driven physics; on
    FilteringEnabled servers those effects will revert.
  • All toggle state is preserved across respawns automatically.
================================================================================
]]

